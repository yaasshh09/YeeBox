"""Golden data for A8: the 2D line source against the Hankel solution.

A time-harmonic line current in free space radiates Ez proportional to
H0^(2)(k rho) (exp(+j w t) convention). The test runs a soft CW source on the
grid and compares the field at probes along +x and along the diagonal with
this, normalized by the value at the first probe of each direction (r0 >= 2
wavelengths), so the source strength drops out.

The grid has its own dispersion, so the Hankel argument uses the numerical
wavenumber of each direction, in closed form:
    axis:     sin(w S / 2) / S = sin(k / 2)
    diagonal: sin(w S / 2) / S = sqrt(2) sin(k / (2 sqrt(2)))
Columns re_c, im_c use the continuum k = w instead, for reference only.

Normalized units: dx = 1, c0 = 1, dt = S. Probe offsets di, dj are in nodes
from the source node.

Usage (from the repo root):
    python validation/gen/line_source_hankel.py
Output: validation/golden/line_source_hankel.csv
"""

from pathlib import Path

import numpy as np
from scipy.special import hankel2

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "validation" / "golden" / "line_source_hankel.csv"

S = 0.5
F0 = 0.05  # cycles per unit time: 20 cells per wavelength, 40 steps per period
W = 2 * np.pi * F0

# Probe offsets from the source node. Axis: r = 40 .. 100 cells. Diagonal:
# (m, m) for m = 29 .. 70, r = m sqrt(2) = 41.0 .. 99.0 cells.
AXIS = [(d, 0) for d in range(40, 101, 5)]
DIAG = [(m, m) for m in range(29, 71, 3)]


def k_axis():
    return 2 * np.arcsin(np.sin(W * S / 2) / S)


def k_diag():
    return 2 * np.sqrt(2) * np.arcsin(np.sin(W * S / 2) / (S * np.sqrt(2)))


def rows(name, offsets, k):
    r = np.array([np.hypot(di, dj) for di, dj in offsets])
    h = hankel2(0, k * r)
    hc = hankel2(0, W * r)
    h, hc = h / h[0], hc / hc[0]
    for (di, dj), ri, v, vc in zip(offsets, r, h, hc):
        # Plain floats, so repr gives the shortest round-trip digits.
        vals = [float(x) for x in (ri, k, v.real, v.imag, vc.real, vc.imag)]
        yield ",".join([name, str(di), str(dj)] + [repr(x) for x in vals])


def main():
    lines = [
        "# A8 golden data, generated by validation/gen/line_source_hankel.py",
        f"# S = {S!r}, f0 = {F0!r}, omega = {W!r}",
        "# H0^(2)(k r) / H0^(2)(k r0), r0 = first row of each direction",
        "direction,di,dj,r,k_num,re,im,re_c,im_c",
    ]
    lines += rows("axis", AXIS, float(k_axis()))
    lines += rows("diagonal", DIAG, float(k_diag()))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(AXIS) + len(DIAG)} rows)")


if __name__ == "__main__":
    main()
