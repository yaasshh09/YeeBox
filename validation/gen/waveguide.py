"""Golden data for A11 and A12: the TM1 mode of a parallel-plate guide.

PEC plates on Ez rows j0 and j0 + a hold Ez = 0, so the discrete TM_m mode
is exactly sin(m pi (j - j0) / a) and ky = m pi / a on the grid too. The
continuum (the gate), with c0 = 1:

    cutoff     f_c = m / (2 a)
    above      beta  = sqrt(w^2 - ky^2),   guided wavelength 2 pi / beta
    below      alpha = sqrt(ky^2 - w^2)

The discrete Yee relation (recorded, not gated) is
(sin(w S / 2) / S)^2 = sin^2(kx / 2) + sin^2(ky / 2), so

    cutoff     sin(w_c S / 2) / S = sin(ky / 2)
    above      sin^2(beta / 2)  = (sin(w S / 2) / S)^2 - sin^2(ky / 2)
    below      sinh^2(alpha / 2) = sin^2(ky / 2) - (sin(w S / 2) / S)^2

Each test frequency has a whole number N of steps per period,
f = 1 / (N S), so a DFT over whole periods has no leakage. A11 measures the
cutoff as the zero of a straight line fitted to beta^2 against w^2 through
the two propagating frequencies; `fc_fit_d` is that fit applied to the
discrete betas, the value a perfect measurement on this grid would give.

Normalized units: dx = 1, c0 = 1, dt = S. Frequencies in cycles per unit
time, beta and alpha in radians (nepers) per cell.

Usage (from the repo root):
    python validation/gen/waveguide.py
Output: validation/golden/waveguide.csv
"""

from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "validation" / "golden" / "waveguide.csv"

S = 0.5
A = 40
M = 1
# Steps per period: 123 and 100 are 1.30 and 1.60 times the continuum cutoff
# (N = 160), 229 is 0.70 times it.
CASES = (("beta", 123), ("beta", 100), ("alpha", 229))

KY = M * np.pi / A


def grid_side(w):
    return (np.sin(w * S / 2) / S) ** 2


def beta_disc(w):
    return 2 * np.arcsin(np.sqrt(grid_side(w) - np.sin(KY / 2) ** 2))


def alpha_disc(w):
    return 2 * np.arcsinh(np.sqrt(np.sin(KY / 2) ** 2 - grid_side(w)))


def main():
    fc_c = M / (2 * A)
    fc_d = (2 / S) * np.arcsin(S * np.sin(KY / 2)) / (2 * np.pi)
    rows, fit = [], []
    for kind, n in CASES:
        f = 1 / (n * S)
        w = 2 * np.pi * f
        if kind == "beta":
            vc, vd = np.sqrt(w**2 - KY**2), beta_disc(w)
            fit.append((w**2, vd**2))
        else:
            vc, vd = np.sqrt(KY**2 - w**2), alpha_disc(w)
        rows.append(",".join([kind, str(n)] + [repr(float(v)) for v in (f, f / fc_c, vc, vd)]))
    (x1, y1), (x2, y2) = fit
    slope = (y2 - y1) / (x2 - x1)
    wc_fit = np.sqrt(x1 - y1 / slope)
    fc_fit_d = wc_fit / (2 * np.pi)
    lines = [
        "# A11, A12 golden data, generated by validation/gen/waveguide.py",
        f"# S = {S!r}, a = {A}, m = {M}",
        f"# fc_c = {float(fc_c)!r}, fc_d = {float(fc_d)!r}, fc_fit_d = {float(fc_fit_d)!r}",
        "kind,steps_per_period,f,f_over_fc,value_c,value_d",
    ] + rows
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} rows)")
    print(f"cutoff: continuum {fc_c:.6f}, discrete {fc_d:.6f} ({fc_d / fc_c - 1:+.3%}), "
          f"fit on discrete betas {fc_fit_d:.6f} ({fc_fit_d / fc_c - 1:+.3%})")
    for kind, n in CASES:
        w = 2 * np.pi / (n * S)
        if kind == "beta":
            print(f"N {n}: guided wavelength discrete vs continuum {np.sqrt(w**2 - KY**2) / beta_disc(w) - 1:+.3%}")
        else:
            print(f"N {n}: alpha discrete vs continuum {alpha_disc(w) / np.sqrt(KY**2 - w**2) - 1:+.3%}")


if __name__ == "__main__":
    main()
