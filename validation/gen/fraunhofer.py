"""Golden data for A22: the Fraunhofer far field of a double slit.

    I(theta) / I(0) = cos^2(pi d sin(theta) / lambda) * sinc^2(pi a sin(theta) / lambda)

with sinc(x) = sin(x) / x, slit width a and center separation d, here
a = 2 lambda and d = 5 lambda (40 and 100 cells at 20 cells per
wavelength). theta is measured from the screen normal, on the far side.

The compare region is fixed here, before any FDTD run: |theta| <= 25 deg,
inside the first zero of the slit envelope (sin theta = lambda / a, 30 deg),
and only where I(theta) is within 10 dB of I(0), so the deep interference
nulls are left out. The formula has no obliquity factor; Kirchhoff's
(1 + cos theta) / 2 would change the pattern by at most the budget printed
below, which is under half the 1 dB gate.

Usage (from the repo root):
    python validation/gen/fraunhofer.py
Output: validation/golden/fraunhofer.csv
"""

from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "validation" / "golden" / "fraunhofer.csv"

A, D = 2.0, 5.0  # slit width and separation, wavelengths
LIMIT = 25.0  # degrees


def intensity(theta):
    u = np.sin(theta)
    return np.cos(np.pi * D * u) ** 2 * np.sinc(A * u) ** 2  # np.sinc(x) = sin(pi x) / (pi x)


def main():
    deg = np.arange(-90, 91)
    th = np.deg2rad(deg)
    db = 10 * np.log10(np.maximum(intensity(th), 1e-300))
    obliquity = 20 * np.log10((1 + np.cos(np.deg2rad(LIMIT))) / 2)
    print(f"obliquity budget over |theta| <= {LIMIT}: {abs(obliquity):.2f} dB")
    assert abs(obliquity) < 0.5
    lines = [
        f"# A22: Fraunhofer double slit, a = {A} lambda, d = {D} lambda, I / I(0) in dB, "
        "theta from the screen normal; generated by validation/gen/fraunhofer.py",
        "theta_deg,fraunhofer_db",
    ]
    lines += [f"{int(t)},{float(v)!r}" for t, v in zip(deg, db)]
    OUT.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines) - 2} rows)")


if __name__ == "__main__":
    main()
