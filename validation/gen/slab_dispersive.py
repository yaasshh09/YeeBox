"""Golden data for A16 (Drude slab) and A17 (Lorentz slab): R and T at normal
incidence on a slab of L cells, vacuum on both sides, from the continuum
complex permittivity.

Convention exp(+j w t), the same as `crates/fdtd-core/src/dispersive.rs`:
    Drude:   eps(w) = eps_inf - wp^2 / (w^2 - j gamma w)
    Lorentz: eps(w) = eps_inf + d_eps w0^2 / (w0^2 - w^2 + 2 j delta w)
Loss is Im(eps) < 0. A complex eps = eps' + j eps'' is a conductivity
sigma = -eps'' w on top of eps', so the Airy formulas of `slab_airy.py`
(`slab_cont`) apply as they are, and numpy's principal square root picks
the decaying branch Im(n) < 0.

The band: only frequencies where the wavelength inside the material,
lambda0 / sqrt(|eps(w)|), is at least 20 cells (docs/04-validation.md).

Normalized units: dx = 1, c0 = 1, dt = S, angular frequencies in radians
per unit time, f in cycles per unit time. Each row carries its material
(drude: a = wp, b = 0, c = gamma; lorentz: a = d_eps, b = w0, c = delta),
so the Rust case builds exactly what was computed here.

Usage (from the repo root):
    python validation/gen/slab_dispersive.py
Output: validation/golden/slab_dispersive.csv
"""

from pathlib import Path

import numpy as np

from slab_airy import slab_cont

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "validation" / "golden" / "slab_dispersive.csv"

S = 0.5
L = 20
MIN_CELLS = 20.0
F_LO, F_HI, F_STEPS = 0.004, 0.045, 42

# Plasma and resonance at f = 0.02, so the band crosses them.
W_P = 2 * np.pi * 0.02
# (kind, eps_inf, a, b, c)
MODELS = (
    ("drude", 1.0, W_P, 0.0, 0.005),
    ("lorentz", 1.0, 2.0, W_P, 0.02),
)


def eps_of(kind, eps_inf, a, b, c, w):
    if kind == "drude":
        return eps_inf - a**2 / (w**2 - 1j * c * w)
    return eps_inf + a * b**2 / (b**2 - w**2 + 2j * c * w)


def rows():
    for model in MODELS:
        for step in range(F_STEPS):
            f = F_LO + (F_HI - F_LO) * step / (F_STEPS - 1)
            w = 2 * np.pi * f
            eps = complex(eps_of(*model, w))
            if (1.0 / f) / np.sqrt(abs(eps)) < MIN_CELLS:
                continue
            r, t = slab_cont(w, eps.real, -eps.imag * w, L)
            vals = list(model[1:]) + [f, r, t]
            yield ",".join([model[0]] + [repr(float(v)) for v in vals])


def main():
    lines = [
        "# A16, A17 golden data, generated by validation/gen/slab_dispersive.py",
        f"# S = {S!r}, L = {L}, slab on nodes 1..L, exp(+jwt), lambda in material >= {MIN_CELLS!r} cells",
        "# drude: a = wp, b = 0, c = gamma. lorentz: a = d_eps, b = w0, c = delta.",
        "kind,eps_inf,a,b,c,f,R_c,T_c",
    ]
    lines += rows()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    n = {k: sum(ln.startswith(k + ",") for ln in lines) for k in ("drude", "lorentz")}
    print(f"wrote {OUT.relative_to(ROOT)} ({n['drude']} drude, {n['lorentz']} lorentz rows)")


if __name__ == "__main__":
    main()
