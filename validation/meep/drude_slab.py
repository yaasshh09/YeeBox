"""Tier 5: the A16 Drude slab in Meep.

The same slab as `cases::dispersive::a16`: 20 cells of a Drude medium with
eps_inf 1, wp = 2 pi 0.02 and gamma = 0.005 (YeeBox normalized units) at
normal incidence, R and T at the 42 frequencies of the golden file
(`validation/golden/slab_dispersive.csv`, the continuum answer).

Like for like with YeeBox:
- One Meep length unit is one YeeBox cell, resolution 1 pixel per unit, so
  Meep frequencies equal YeeBox frequencies; Courant 0.5.
- Meep's Drude is eps_inf - sigma f_n^2 / (f (f + i gamma_n)) in its
  exp(-i w t) convention, which is YeeBox's eps_inf - wp^2 / (w (w - j
  gamma)) in exp(+j w t) with f_n = wp / (2 pi) and gamma_n = gamma / (2 pi).
- R and T from two flux planes, divided by the incident flux of a run
  without the slab, as `spectra::rt_spectrum` does.

Usage (inside the WSL conda env, from the repo root):
    python validation/meep/drude_slab.py
Output: validation/meep/drude_slab.csv
"""

import csv
from pathlib import Path

import meep as mp
import numpy as np

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = HERE / "drude_slab.csv"

WP, GAMMA, L = 2 * np.pi * 0.02, 0.005, 20


def golden():
    rows = []
    with open(ROOT / "validation" / "golden" / "slab_dispersive.csv") as f:
        for r in csv.reader(line for line in f if not line.startswith("#")):
            if r[0] == "drude":
                rows.append((float(r[5]), float(r[6]), float(r[7])))
    return rows


def main():
    rows = golden()
    freqs = [r[0] for r in rows]
    dpml, space = 32, 60
    sz = 2 * (dpml + space) + L
    cell = mp.Vector3(0, 0, sz)
    z_src = -sz / 2 + dpml + 5
    z_r = z_src + 10
    z_t = sz / 2 - dpml - 5
    fcen, df = 0.025, 0.05
    src = [mp.Source(mp.GaussianSource(fcen, fwidth=df), component=mp.Ex, center=mp.Vector3(z=z_src))]
    drude = mp.Medium(
        epsilon=1.0,
        E_susceptibilities=[
            mp.DrudeSusceptibility(frequency=WP / (2 * np.pi), gamma=GAMMA / (2 * np.pi), sigma=1.0)
        ],
    )

    def sim(geometry):
        return mp.Simulation(
            cell_size=cell,
            resolution=1,
            dimensions=1,
            boundary_layers=[mp.PML(dpml)],
            sources=src,
            geometry=geometry,
            eps_averaging=False,
            Courant=0.5,
        )

    empty = sim([])
    refl = empty.add_flux(freqs, mp.FluxRegion(center=mp.Vector3(z=z_r)))
    tran = empty.add_flux(freqs, mp.FluxRegion(center=mp.Vector3(z=z_t)))
    empty.run(until_after_sources=mp.stop_when_dft_decayed(tol=1e-9))
    inc = np.array(mp.get_fluxes(tran))
    inc_data = empty.get_flux_data(refl)

    # Centered half a pixel off the grid so both faces fall between pixel
    # centers: exactly 20 pixels, as YeeBox's slab is 20 cells with faces at
    # half cells. Centered on a pixel, the faces sit on pixel centers and
    # the slab takes a 21st pixel (2.4e-2 against the golden file instead
    # of 1.8e-3).
    slab = mp.Block(size=mp.Vector3(mp.inf, mp.inf, L), center=mp.Vector3(z=0.5), material=drude)
    full = sim([slab])
    refl = full.add_flux(freqs, mp.FluxRegion(center=mp.Vector3(z=z_r)))
    tran = full.add_flux(freqs, mp.FluxRegion(center=mp.Vector3(z=z_t)))
    full.load_minus_flux_data(refl, inc_data)
    full.run(until_after_sources=mp.stop_when_dft_decayed(tol=1e-9))
    r = -np.array(mp.get_fluxes(refl)) / inc
    t = np.array(mp.get_fluxes(tran)) / inc

    worst = max(max(abs(a - g[1]), abs(b - g[2])) for a, b, g in zip(r, t, rows))
    print(f"worst |R - R_c|, |T - T_c|: {worst:.2e}")
    lines = [
        "# Tier 5: Drude slab (eps_inf 1, wp 2 pi 0.02, gamma 0.005, 20 cells), Meep at one "
        "pixel per cell, Courant 0.5, no smoothing; R_c, T_c from the golden file; "
        "generated by validation/meep/drude_slab.py",
        "f,R_meep,T_meep,R_c,T_c",
    ]
    for f, a, b, g in zip(freqs, r, t, rows):
        lines.append(f"{f!r},{float(a)!r},{float(b)!r},{g[1]!r},{g[2]!r}")
    OUT.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"wrote {OUT.name}")


if __name__ == "__main__":
    main()
