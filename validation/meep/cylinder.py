"""Tier 5: the A20 dielectric cylinder in Meep.

The same physics as `cases::scattering::a20` at the gated radius: an eps 4
cylinder of radius 40 cells under a plane wave travelling along +x, Ez
polarized (TMz), scattering width at k a = 1, 2, 5 over every degree.

Like for like with YeeBox:
- Meep's length unit is the cylinder radius, at resolution 40, so one Meep
  pixel is one YeeBox cell and f_meep = 40 f_yeebox = k a / (2 pi).
- Courant number 0.5 (Meep's default, YeeBox's too).
- No subpixel smoothing (eps_averaging=False): YeeBox staircases. A second
  run with Meep's default smoothing is recorded beside it.
- The scattered field: Meep has no TF/SF box, so it runs the empty cell
  first and subtracts its near-to-far data (load_minus_near2far_data).
  The incident phasor comes from a DFT point at the center of the empty run.
- The far field is read 1e6 radii out and turned into sigma = 2 pi R |Es|^2
  / |Einc|^2, reported as sigma / lambda in dB like the golden series.

The source is a Gaussian line current spanning the whole cell height,
PML included, the usual Meep plane wave without a periodic boundary.

Usage (inside the WSL conda env, from the repo root):
    python validation/meep/cylinder.py
Output: validation/meep/cylinder.csv
"""

from pathlib import Path

import meep as mp
import numpy as np

OUT = Path(__file__).resolve().parent / "cylinder.csv"

KA = [1.0, 2.0, 5.0]
EPS = 4.0
RES = 40  # pixels per radius = YeeBox cells per radius


def run(smoothing):
    r = 1.0
    dpml = 16 / RES  # 16 cells, as the YeeBox layer
    gap = 1.0
    s = 2 * (r + gap + dpml)
    cell = mp.Vector3(s, s)
    freqs = [ka / (2 * np.pi) for ka in KA]
    fcen, df = 0.5, 0.9
    src = [
        mp.Source(
            mp.GaussianSource(fcen, fwidth=df, is_integrated=True),
            component=mp.Ez,
            center=mp.Vector3(-s / 2 + dpml),
            size=mp.Vector3(0, s),
        )
    ]
    box = r + 0.5 * gap
    regions = [
        mp.Near2FarRegion(center=mp.Vector3(box, 0), size=mp.Vector3(0, 2 * box), weight=+1),
        mp.Near2FarRegion(center=mp.Vector3(-box, 0), size=mp.Vector3(0, 2 * box), weight=-1),
        mp.Near2FarRegion(center=mp.Vector3(0, box), size=mp.Vector3(2 * box, 0), weight=+1),
        mp.Near2FarRegion(center=mp.Vector3(0, -box), size=mp.Vector3(2 * box, 0), weight=-1),
    ]

    def sim(geometry):
        return mp.Simulation(
            cell_size=cell,
            resolution=RES,
            boundary_layers=[mp.PML(dpml)],
            sources=src,
            geometry=geometry,
            eps_averaging=smoothing,
            Courant=0.5,
        )

    empty = sim([])
    n2f = empty.add_near2far(freqs, *regions)
    inc = empty.add_dft_fields([mp.Ez], freqs, center=mp.Vector3(), size=mp.Vector3())
    empty.run(until_after_sources=mp.stop_when_dft_decayed(tol=1e-8))
    data = empty.get_near2far_data(n2f)
    e_inc = [
        complex(np.asarray(empty.get_dft_array(inc, mp.Ez, k)).ravel()[0])
        for k in range(len(freqs))
    ]

    full = sim([mp.Cylinder(radius=r, material=mp.Medium(epsilon=EPS))])
    n2f = full.add_near2far(freqs, *regions)
    full.load_minus_near2far_data(n2f, data)
    full.run(until_after_sources=mp.stop_when_dft_decayed(tol=1e-8))

    big = 1e6
    out = {}
    for k, (ka, f) in enumerate(zip(KA, freqs)):
        lam = 1.0 / f
        row = []
        for deg in range(360):
            p = np.deg2rad(deg)
            ff = full.get_farfield(n2f, mp.Vector3(big * np.cos(p), big * np.sin(p)))
            ez = ff[6 * k + 2]
            sigma = 2 * np.pi * big * abs(ez) ** 2 / abs(e_inc[k]) ** 2
            row.append(10 * np.log10(sigma / lam))
        out[ka] = row
    return out


def main():
    stair = run(False)
    smooth = run(True)
    lines = [
        "# Tier 5: eps 4 cylinder, radius 40 cells (Meep resolution 40 per radius), TMz, "
        "sigma / lambda in dB; meep_staircase without subpixel smoothing (like YeeBox), "
        "meep_smoothed with Meep's default; generated by validation/meep/cylinder.py",
        "ka,phi_deg,meep_staircase_db,meep_smoothed_db",
    ]
    for ka in KA:
        for deg in range(360):
            lines.append(f"{ka!r},{deg},{float(stair[ka][deg])!r},{float(smooth[ka][deg])!r}")
    OUT.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"wrote {OUT.name}")


if __name__ == "__main__":
    main()
