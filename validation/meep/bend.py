"""Tier 5: transmission around a 90 degree waveguide bend, in Meep.

The bend of the Meep tutorial: a 16 x 16 cell, an eps 12 guide one unit wide
along x at y = -3.5 that turns up at x = 3.5 and runs out through +y, a
one-unit PML, Ez polarization (TMz), resolution 10. T(f) is the flux into
the bent arm over the flux down a straight guide, at 100 frequencies from
0.1 to 0.2 (units of c / unit). `cases::tier5::bend` builds the same scene
in YeeBox.

Like for like with YeeBox:
- Resolution 10: one Meep pixel is one YeeBox cell, f_yeebox = f_meep / 10.
- Courant 0.5, no subpixel smoothing.
- Every guide face sits half a pixel off the grid, so the guide is exactly
  10 pixels wide, as YeeBox's is 10 nodes (faces at half cells). With a
  face on a pixel center the guide would take an 11th pixel.
- The source is a Gaussian line current across the guide, the flux planes
  span twice the guide width, as in the tutorial.

Usage (inside the WSL conda env, from the repo root):
    python validation/meep/bend.py
Output: validation/meep/bend.csv
"""

from pathlib import Path

import meep as mp
import numpy as np

OUT = Path(__file__).resolve().parent / "bend.csv"

RES = 10
SX = SY = 16.0
DPML = 1.0
W = 1.0
EPS = 12.0
YC = -3.5  # the input guide's center line
XC = 3.5  # the output guide's center line
HALF = 0.5 / RES  # half a pixel
FREQS = list(np.linspace(0.1, 0.2, 100))


def run(bent):
    guide = mp.Medium(epsilon=EPS)
    if bent:
        geometry = [
            mp.Block(
                size=mp.Vector3(SX / 2 + XC + W / 2, W),
                center=mp.Vector3(-SX / 4 + (XC + W / 2) / 2 + HALF, YC + HALF),
                material=guide,
            ),
            mp.Block(
                size=mp.Vector3(W, SY / 2 - YC + W / 2),
                center=mp.Vector3(XC + HALF, SY / 4 + (YC - W / 2) / 2 + HALF),
                material=guide,
            ),
        ]
    else:
        geometry = [
            mp.Block(size=mp.Vector3(mp.inf, W), center=mp.Vector3(0, YC + HALF), material=guide)
        ]
    src = [
        mp.Source(
            mp.GaussianSource(0.15, fwidth=0.1),
            component=mp.Ez,
            center=mp.Vector3(-SX / 2 + DPML + 0.5, YC + HALF),
            size=mp.Vector3(0, W),
        )
    ]
    sim = mp.Simulation(
        cell_size=mp.Vector3(SX, SY),
        resolution=RES,
        boundary_layers=[mp.PML(DPML)],
        sources=src,
        geometry=geometry,
        eps_averaging=False,
        Courant=0.5,
    )
    if bent:
        region = mp.FluxRegion(
            center=mp.Vector3(XC + HALF, SY / 2 - DPML - 0.5), size=mp.Vector3(2 * W, 0)
        )
    else:
        region = mp.FluxRegion(
            center=mp.Vector3(SX / 2 - DPML - 0.5, YC + HALF), size=mp.Vector3(0, 2 * W)
        )
    flux = sim.add_flux(FREQS, region)
    sim.run(until_after_sources=mp.stop_when_dft_decayed(tol=1e-8))
    return np.array(mp.get_fluxes(flux))


def main():
    straight = run(False)
    bend = run(True)
    t = bend / straight
    lines = [
        "# Tier 5: 90 degree bend in an eps 12 guide one unit wide (Meep tutorial), resolution 10, "
        "Courant 0.5, no smoothing; f in c / unit (f_yeebox = f / 10); "
        "generated by validation/meep/bend.py",
        "f,T_meep",
    ]
    lines += [f"{float(f)!r},{float(v)!r}" for f, v in zip(FREQS, t)]
    OUT.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"T from {t.min():.3f} to {t.max():.3f}; wrote {OUT.name}")


if __name__ == "__main__":
    main()
