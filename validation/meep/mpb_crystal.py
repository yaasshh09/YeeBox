"""Tier 5: MPB band edges for the A24 photonic crystal.

eps 8.9 rods of radius 0.2 a on a square lattice in air, TM polarization
(E along the rods, YeeBox's TMz). Two things:

1. The complete TM gap over the irreducible zone (Gamma, X, M, Gamma), to
   confirm the value the docs quote (about 0.32 to 0.44 c / a; Joannopoulos
   et al., Photonic Crystals, chapter 5).
2. Bands 1 to 4 along Gamma-X, the normal-incidence direction A24 measures.

Usage (inside the WSL conda env, from the repo root):
    python validation/meep/mpb_crystal.py
Output: validation/meep/mpb_crystal.csv
"""

from pathlib import Path

import meep as mp
import numpy as np
from meep import mpb

OUT = Path(__file__).resolve().parent / "mpb_crystal.csv"


def bands(k_points):
    ms = mpb.ModeSolver(
        num_bands=4,
        k_points=k_points,
        geometry=[mp.Cylinder(0.2, material=mp.Medium(epsilon=8.9))],
        geometry_lattice=mp.Lattice(size=mp.Vector3(1, 1)),
        resolution=64,
    )
    ms.run_tm()
    return np.array(ms.all_freqs)


def main():
    gamma, x, m = mp.Vector3(), mp.Vector3(0.5), mp.Vector3(0.5, 0.5)
    zone = bands(mp.interpolate(16, [gamma, x, m, gamma]))
    lo, hi = zone[:, 0].max(), zone[:, 1].min()
    gx_k = mp.interpolate(32, [gamma, x])
    gx = bands(gx_k)
    print(f"complete TM gap {lo:.4f} to {hi:.4f} c / a")
    print(f"Gamma-X: band 1 top {gx[:, 0].max():.4f}, band 2 bottom {gx[:, 1].min():.4f}")
    lines = [
        "# Tier 5: MPB, eps 8.9 rods r = 0.2 a, square lattice, TM, resolution 64; "
        f"complete gap {float(lo)!r} to {float(hi)!r} c / a; "
        "generated by validation/meep/mpb_crystal.py",
        "kx,band1,band2,band3,band4",
    ]
    for k, row in zip(gx_k, gx):
        lines.append(",".join([repr(float(k.x))] + [repr(float(v)) for v in row]))
    OUT.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"wrote {OUT.name}")


if __name__ == "__main__":
    main()
